# Fish, Animals and Ores have to have dividers to keep the catalogue organized and easy to read. 
# Adding pages to the catalogue is a good idea. One page for food and drinksm one for key items, one for books and watches, etc.

ITEMS_PER_PAGE = 10


def form_pages_by_type(available_items):
    """Groups items by type, then cuts each group into pages of ITEMS_PER_PAGE items.
    Returns a list of pages. Each page is (type, part number, number of parts, list of (item, details))."""
    groups = {}
    for item, details in available_items.items():
        groups.setdefault(details.get("type", "misc"), []).append((item, details))

    pages = []
    for item_type, items in groups.items():
        parts = [items[i:i + ITEMS_PER_PAGE] for i in range(0, len(items), ITEMS_PER_PAGE)]
        for part_number, part in enumerate(parts, start=1):
            pages.append((item_type, part_number, len(parts), part))
    return pages


def format_item(item, details):
    line = f"- {item}: ${details['price']}"
    if "health" in details or "energy" in details:
        line += f" | Health: {details.get('health', 0)}, Energy: {details.get('energy', 0)}"
        if "shelf_life" in details:
            line += f", Shelf life: {details['shelf_life']}s"
    if "desc" in details:
        line += f" | {details['desc'].strip()}"
    return line


def show_page(pages, index):
    item_type, part_number, total_parts, items = pages[index]
    title = item_type.capitalize()
    if total_parts > 1:
        title += f" ({part_number}/{total_parts})"
    print()
    print(f"=== Shop - {title} - page {index + 1} of {len(pages)} ===")
    for item, details in items:
        print(format_item(item, details))


def show_shoplist():
    pages = form_pages_by_type(available)
    page_types = []
    for item_type, _, _, _ in pages:
        if item_type not in page_types:
            page_types.append(item_type)

    index = 0
    while True:
        show_page(pages, index)
        print(f"Categories: {', '.join(page_types)}")
        choice = input("[n]ext, [p]revious, page number, category name, or [q]uit: ").strip().lower()

        if choice in ("q", "quit", "exit", ""):
            break
        elif choice in ("n", "next"):
            index = (index + 1) % len(pages)
        elif choice in ("p", "prev", "previous"):
            index = (index - 1) % len(pages)
        elif choice.isdigit() and 1 <= int(choice) <= len(pages):
            index = int(choice) - 1
        elif choice in page_types:
            index = next(i for i, page in enumerate(pages) if page[0] == choice)
        else:
            print("Unknown choice. Try again.")
